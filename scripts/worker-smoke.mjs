const base = process.env.WORKER_SMOKE_URL ?? 'http://127.0.0.1:8788';
const request = async (path, method = 'GET', body, cookie) => {
  const headers = {};
  if (body !== undefined) headers['content-type'] = 'application/json';
  if (cookie) headers.cookie = cookie;
  const response = await fetch(`${base}${path}`, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
  const data = await response.json().catch(() => null);
  return { response, data };
};
const health = await request('/api/health');
if (health.response.status !== 200 || health.data?.status !== 'ok') throw new Error('Worker health check failed');
const email = `worker-smoke-${Date.now()}@example.test`;
const registration = await request('/api/auth/register', 'POST', { name: 'Worker Smoke', email, password: 'correct-horse-battery' });
if (registration.response.status !== 201) throw new Error(`Registration failed: ${registration.response.status} ${JSON.stringify(registration.data)}`);
const cookie = registration.response.headers.get('set-cookie')?.split(';')[0];
if (!cookie?.startsWith('scopebeacon_session=')) throw new Error('Session cookie was not issued');
const project = await request('/api/projects', 'POST', { name: 'Worker migration test', description: 'D1 smoke test' }, cookie);
if (project.response.status !== 201) throw new Error('Project creation failed');
const projectId = project.data.project.id;
const task = await request(`/api/projects/${projectId}/tasks`, 'POST', { title: 'Private internal task detail' }, cookie);
if (task.response.status !== 201) throw new Error('Task creation failed');
const milestone = await request(`/api/projects/${projectId}/milestones`, 'POST', { title: 'Public milestone' }, cookie);
if (milestone.response.status !== 201) throw new Error('Milestone creation failed');
const share = await request(`/api/projects/${projectId}/share`, 'POST', { enabled: true }, cookie);
const token = share.data?.token;
const publicView = await request(`/api/public/${token}`);
if (publicView.response.status !== 200 || publicView.data?.milestones?.[0]?.title !== 'Public milestone') throw new Error('Public progress view failed');
if (JSON.stringify(publicView.data).includes('Private internal task detail')) throw new Error('Private task data leaked to public response');
const revoke = await request(`/api/projects/${projectId}/share`, 'POST', { enabled: false }, cookie);
const revoked = await request(`/api/public/${token}`);
if (revoke.response.status !== 200 || revoked.response.status !== 404) throw new Error('Share revocation failed');
const me = await request('/api/auth/me', 'GET', undefined, cookie);
if (me.response.status !== 200 || me.data.user.email !== email) throw new Error('Session validation failed');
console.log(JSON.stringify({ health: health.response.status, registration: registration.response.status, project: project.response.status, task: task.response.status, milestone: milestone.response.status, publicShare: publicView.response.status, revokedShare: revoked.response.status, session: me.response.status, privateTaskExcluded: true }));
